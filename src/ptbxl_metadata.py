"""Standalone PTB-XL metadata validation and prospective rhythm-cohort audit.

No waveforms, splits, balancing or model targets are generated. Existing phase-11
SCP parsing is reused and hardened against duplicate dictionary keys.
"""
import ast
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
import re
import numpy as np
import pandas as pd
from .rhythm_audit import parse_scp_codes
from .prepare_dataset import sha256_file

DEFAULT_METADATA_DIR = Path(__file__).resolve().parents[1]/'data/ptbxl/metadata'
CORE_TARGETS = ('SR','AFIB','STACH','SBRAD')
REQUIRED_COLUMNS = ('ecg_id','patient_id','scp_codes','strat_fold','filename_lr','filename_hr')
QUALITY_COLUMNS = ('validated_by','second_opinion','initial_autogenerated_report','validated_by_human',
                   'baseline_drift','static_noise','burst_noise','electrodes_problems','extra_beats','pacemaker')


class MetadataValidationError(ValueError):
    """Malformed source metadata must be corrected/reviewed, never silently relabeled."""


def parse_statement_dict(value):
    """Parse with literal_eval via the existing safe parser; reject duplicate keys."""
    if isinstance(value,str):
        try:
            node=ast.parse(value,mode='eval').body
        except (SyntaxError,ValueError) as exc:
            raise MetadataValidationError('Malformed scp_codes literal') from exc
        if not isinstance(node,ast.Dict):
            raise MetadataValidationError('scp_codes must be a literal dictionary')
        try:
            keys=[ast.literal_eval(key) for key in node.keys]
        except (ValueError,TypeError) as exc:
            raise MetadataValidationError('Nonliteral SCP dictionary key') from exc
        if any(not isinstance(key,str) for key in keys) or len(keys)!=len(set(keys)):
            raise MetadataValidationError('Invalid or duplicate SCP dictionary keys')
    try:
        return parse_scp_codes(value)
    except ValueError as exc:
        raise MetadataValidationError(str(exc)) from exc


def _integer_column(series,name):
    numeric=pd.to_numeric(series,errors='coerce').to_numpy(dtype=float)
    if (not np.isfinite(numeric).all() or np.any(numeric<1) or np.any(numeric%1!=0)
            or np.any(numeric>=np.iinfo(np.int64).max)
            or any(isinstance(v,(bool,np.bool_)) for v in series)):
        raise MetadataValidationError(f'{name}: need nonmissing positive integer identifiers')
    return numeric.astype(np.int64)


@dataclass(frozen=True)
class PTBMetadata:
    """Original CSV rows plus separate validated numerical IDs and parsed statements."""
    records: pd.DataFrame
    definitions: pd.DataFrame
    ecg_ids: np.ndarray
    patient_ids: np.ndarray
    folds: np.ndarray
    statements: tuple[dict, ...]
    rhythm_codes: tuple[str, ...]
    provenance: dict


def validate_metadata_frames(records,definitions,*,provenance=None):
    """Validate structural metadata, leaving the input DataFrames unchanged.

    Conflicting patient folds are reported by audit_metadata rather than reassigned.
    Optional demographic/quality nulls are counted, not interpreted as clean/normal.
    Paths are checked syntactically; waveform files are deliberately not required.
    """
    missing=set(REQUIRED_COLUMNS)-set(records.columns)
    if missing:
        raise MetadataValidationError(f'Missing record columns: {sorted(missing)}')
    if not {'description','diagnostic','form','rhythm'}.issubset(definitions.columns):
        raise MetadataValidationError('SCP definitions lack required descriptions/category flags')
    if definitions.index.has_duplicates or definitions.index.isna().any() or any(not isinstance(k,str) or not k.strip() for k in definitions.index):
        raise MetadataValidationError('SCP definition codes must be unique nonempty strings')
    if definitions['description'].isna().any() or any(not isinstance(v,str) or not v.strip() for v in definitions['description']):
        raise MetadataValidationError('SCP description missing')
    for category in ('diagnostic','form','rhythm'):
        original=definitions[category]
        values=pd.to_numeric(original,errors='coerce')
        if (original.notna() & values.isna()).any() or not values.dropna().isin([0,1]).all():
            raise MetadataValidationError(f'Invalid definition category flag: {category}')
    ecg=_integer_column(records['ecg_id'],'ecg_id')
    patients=_integer_column(records['patient_id'],'patient_id')
    folds=_integer_column(records['strat_fold'],'strat_fold')
    if len(np.unique(ecg))!=len(ecg):
        raise MetadataValidationError('Duplicate ecg_id')
    if np.any(folds>10):
        raise MetadataValidationError('strat_fold must be in 1..10')
    for column,rate,suffix in [('filename_lr',100,'lr'),('filename_hr',500,'hr')]:
        for eid,path in zip(ecg,records[column]):
            match=re.fullmatch(rf'records{rate}/(\d{{5}})/(\d{{5}})_{suffix}',path) if isinstance(path,str) else None
            if match is None or int(match[2])!=eid or int(match[1])!=eid//1000*1000:
                raise MetadataValidationError(f'{column}: invalid path or ECG identifier for ecg_id {eid}')
    statements=[]
    for eid,value in zip(ecg,records['scp_codes']):
        try:
            parsed=parse_statement_dict(value)
        except MetadataValidationError as exc:
            raise MetadataValidationError(f'ecg_id {eid}: {exc}') from exc
        undefined=set(parsed)-set(definitions.index)
        if undefined:
            raise MetadataValidationError(f'ecg_id {eid}: undefined SCP codes {sorted(undefined)}')
        statements.append(parsed)
    rhythms=tuple(definitions.index[pd.to_numeric(definitions['rhythm'],errors='coerce').fillna(0)==1])
    if not rhythms:
        raise MetadataValidationError('No rhythm definitions found')
    return PTBMetadata(records.copy(deep=True),definitions.copy(deep=True),ecg,patients,folds,
                       tuple(statements),rhythms,dict(provenance or {}))


def load_ptb_metadata(metadata_dir=DEFAULT_METADATA_DIR):
    """Read the two local metadata CSVs only; never download or open waveform files."""
    directory=Path(metadata_dir)
    paths={name:directory/name for name in ('ptbxl_database.csv','scp_statements.csv')}
    for path in paths.values():
        if not path.is_file():
            raise FileNotFoundError(f'Metadata missing: {path}; obtain the official PTB-XL 1.0.3 CSV, not waveform archives')
    records=pd.read_csv(paths['ptbxl_database.csv'])
    definitions=pd.read_csv(paths['scp_statements.csv'],index_col=0)
    return validate_metadata_frames(records,definitions,provenance={
        'requested_version':'1.0.3','official_source':'https://physionet.org/content/ptb-xl/1.0.3/',
        'files':{name:{'bytes':path.stat().st_size,'sha256':sha256_file(path)} for name,path in paths.items()},
        'version_evidence':'Locally supplied files requested from versioned official URLs; cardinality/schema checked separately; remote signature not independently verified'})


def _fold_counts(data,mask,patients=False):
    return {str(f):int(len(np.unique(data.patient_ids[mask & (data.folds==f)]))) if patients
            else int(np.count_nonzero(mask & (data.folds==f))) for f in range(1,11)}


def propose_exclusive_cohort(data, target_codes=CORE_TARGETS):
    """Audit ONLY: keep exactly one of ALL rhythm codes, and that code in target set.

    No source row is removed, no split is created, no class indices are assigned.
    Multiple rhythm tags are never resolved by a priority or likelihood threshold.
    Non-rhythm diagnostic/form labels and quality flags are retained, not filtered.
    """
    target_codes=tuple(target_codes)
    if not target_codes or len(set(target_codes))!=len(target_codes) or not set(target_codes).issubset(data.rhythm_codes):
        raise MetadataValidationError('Targets must be unique known rhythm codes')
    rhythm_set=set(data.rhythm_codes)
    rows=[]
    eligible=np.zeros(len(data.ecg_ids),dtype=bool)
    for i,statements in enumerate(data.statements):
        codes=sorted(set(statements)&rhythm_set)
        if not codes:
            reason='no_rhythm_statement'
        elif len(codes)>1:
            reason='multiple_rhythm_statements'
        elif codes[0] not in target_codes:
            reason='single_rhythm_outside_proposed_targets'
        else:
            reason='proposed_eligible'
            eligible[i]=True
        rows.append({'ecg_id':int(data.ecg_ids[i]),'patient_id':int(data.patient_ids[i]),
                     'strat_fold':int(data.folds[i]),'original_rhythm_codes':codes,
                     'proposal_status':reason,'proposed_label':codes[0] if eligible[i] else None})
    per_class={}
    for code in data.rhythm_codes:
        mask=np.array([code in row for row in data.statements],dtype=bool)
        after=mask & eligible
        per_class[code]={'records_before':int(mask.sum()),'patients_before':int(len(np.unique(data.patient_ids[mask]))),
            'records_after':int(after.sum()),'patients_after':int(len(np.unique(data.patient_ids[after]))),
            'records_after_by_fold':_fold_counts(data,after),
            'patients_after_by_fold':_fold_counts(data,after,True)}
    return {'targets':list(target_codes),'rule':'Exactly one original rhythm-flagged code, in the proposed target set; no quality/likelihood/diagnostic exclusions',
        'source_record_count':len(rows),'proposed_record_count':int(eligible.sum()),
        'proposed_patient_count':int(len(np.unique(data.patient_ids[eligible]))),
        'mutually_exclusive_exclusion_reasons':dict(Counter(r['proposal_status'] for r in rows)),
        'per_class':per_class,'record_audit':rows}


def audit_metadata(data, target_codes=CORE_TARGETS):
    """Count dictionary-key presence, preserving reported likelihoods, including zero."""
    n=len(data.ecg_ids)
    rhythm_set=set(data.rhythm_codes)
    masks={code:np.array([code in d for d in data.statements],dtype=bool) for code in data.rhythm_codes}
    counts=[]
    for code in data.rhythm_codes:
        mask=masks[code]
        scores=Counter(format(float(d[code]),'.15g') for d in data.statements if code in d)
        counts.append({'code':code,'description':data.definitions.loc[code,'description'],
            'record_count':int(mask.sum()),'patient_count':int(len(np.unique(data.patient_ids[mask]))),
            'record_percent':100*int(mask.sum())/n if n else 0.,
            'records_by_fold':_fold_counts(data,mask),'patients_by_fold':_fold_counts(data,mask,True),
            'likelihood_counts':dict(sorted(scores.items())),
            'zero_likelihood_records':scores.get('0',0),
            'minimum_fold_patient_count':min(_fold_counts(data,mask,True).values()),
            'missing_record_folds':[f for f,c in _fold_counts(data,mask).items() if c==0]})
    co=[]
    for a in data.rhythm_codes:
        for b in data.rhythm_codes:
            mask=masks[a]&masks[b]
            co.append({'code_a':a,'code_b':b,'record_count':int(mask.sum()),
                       'patient_count':int(len(np.unique(data.patient_ids[mask])))})
    patient_folds={}
    for patient,fold in zip(data.patient_ids,data.folds):
        patient_folds.setdefault(int(patient),set()).add(int(fold))
    conflicts={str(pid):sorted(folds) for pid,folds in patient_folds.items() if len(folds)>1}
    pattern_counts=Counter(tuple(sorted(set(d)&rhythm_set)) for d in data.statements)
    norms=np.array(['NORM' in d for d in data.statements],dtype=bool)
    sr=masks.get('SR',np.zeros(n,dtype=bool))
    definitions=[]
    for code,row in data.definitions.iterrows():
        definitions.append({'code':code,'description':row['description'],
            **{category:False if pd.isna(row[category]) else bool(float(row[category]))
               for category in ('diagnostic','form','rhythm')}})
    proposal=propose_exclusive_cohort(data,target_codes)
    return {'schema_version':'ptbxl-metadata-audit-v1','provenance':data.provenance,
        'record_count':n,'patient_count':len(patient_folds),'definition_count':len(definitions),
        'matches_published_1_0_3_cardinalities':n==21799 and len(patient_folds)==18869 and len(definitions)==71,
        'rhythm_codes':list(data.rhythm_codes),'rhythm_counts':counts,'definitions':definitions,
        'missing_values_by_column':{str(k):int(v) for k,v in data.records.isna().sum().items()},
        'optional_quality_columns_missing':sorted(set(QUALITY_COLUMNS)-set(data.records.columns)),
        'empty_statement_dictionaries':sum(not d for d in data.statements),
        'records_without_rhythm':sum(c for codes,c in pattern_counts.items() if not codes),
        'records_with_multiple_rhythms':sum(c for codes,c in pattern_counts.items() if len(codes)>1),
        'rhythm_combinations':[{'codes':list(codes),'record_count':count} for codes,count in sorted(pattern_counts.items())],
        'cooccurrence':co,'patient_fold_conflict_count':len(conflicts),'patient_fold_conflicts':conflicts,
        'fold_record_counts':{str(f):int(np.count_nonzero(data.folds==f)) for f in range(1,11)},
        'fold_patient_counts':{str(f):int(len(np.unique(data.patient_ids[data.folds==f]))) for f in range(1,11)},
        'NORM_without_SR':int(np.count_nonzero(norms&~sr)),'SR_without_NORM':int(np.count_nonzero(sr&~norms)),
        'proposal':proposal,'count_rule':'Original dictionary-key presence; score 0 means unknown likelihood, not confirmed absence',
        'path_validation':'Syntactic records100/_lr and records500/_hr ECG/folder consistency only; no waveform availability checked',
        'no_waveforms_processed':True,'no_splits_created':True,'no_balancing':True}
